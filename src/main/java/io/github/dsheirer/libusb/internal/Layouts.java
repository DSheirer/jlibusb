package io.github.dsheirer.libusb.internal;

import static java.lang.foreign.MemoryLayout.PathElement.groupElement;
import static java.lang.foreign.MemoryLayout.structLayout;
import static java.lang.foreign.ValueLayout.ADDRESS;
import static java.lang.foreign.ValueLayout.JAVA_BYTE;
import static java.lang.foreign.ValueLayout.JAVA_INT;
import static java.lang.foreign.ValueLayout.JAVA_LONG;
import static java.lang.foreign.ValueLayout.JAVA_SHORT;

import java.lang.foreign.GroupLayout;
import java.lang.foreign.MemoryLayout;
import java.lang.foreign.MemorySegment;
import java.lang.foreign.SegmentAllocator;
import java.time.Duration;
import java.util.Locale;

/**
 * Memory layouts and constants from {@code libusb.h}.
 *
 * <p>Written by hand rather than generated by jextract. Apart from pointers and
 * {@code struct timeval}, every field has a fixed width, and every supported
 * platform is 64-bit, so one set of layouts is correct on all of them.
 */
public final class Layouts {
    // ---- Error codes, enum libusb_error ----
    public static final int SUCCESS = 0;
    public static final int ERROR_ACCESS = -3;
    public static final int ERROR_NO_DEVICE = -4;
    public static final int ERROR_BUSY = -6;
    public static final int ERROR_NOT_SUPPORTED = -12;

    // ---- Capabilities, enum libusb_capability ----
    public static final int CAP_HAS_CAPABILITY = 0x0000;
    public static final int CAP_HAS_HOTPLUG = 0x0001;
    public static final int CAP_HAS_HID_ACCESS = 0x0100;
    public static final int CAP_SUPPORTS_DETACH_KERNEL_DRIVER = 0x0101;

    // ---- Hotplug ----
    public static final int HOTPLUG_EVENT_DEVICE_ARRIVED = 0x01;
    public static final int HOTPLUG_EVENT_DEVICE_LEFT = 0x02;
    public static final int HOTPLUG_ENUMERATE = 0x01;
    public static final int HOTPLUG_MATCH_ANY = -1;

    // ---- Options, enum libusb_option ----
    public static final int OPTION_LOG_LEVEL = 0;

    /** Most port numbers in a path: the USB 3.0 specification allows a depth of 7. */
    public static final int MAX_PORT_DEPTH = 7;

    /** {@code struct libusb_version}. */
    public static final GroupLayout VERSION = structLayout(
        JAVA_SHORT.withName("major"),
        JAVA_SHORT.withName("minor"),
        JAVA_SHORT.withName("micro"),
        JAVA_SHORT.withName("nano"),
        ADDRESS.withName("rc"),
        ADDRESS.withName("describe"));

    /** {@code struct libusb_device_descriptor}. */
    public static final GroupLayout DEVICE_DESCRIPTOR = structLayout(
        JAVA_BYTE.withName("bLength"),
        JAVA_BYTE.withName("bDescriptorType"),
        JAVA_SHORT.withName("bcdUSB"),
        JAVA_BYTE.withName("bDeviceClass"),
        JAVA_BYTE.withName("bDeviceSubClass"),
        JAVA_BYTE.withName("bDeviceProtocol"),
        JAVA_BYTE.withName("bMaxPacketSize0"),
        JAVA_SHORT.withName("idVendor"),
        JAVA_SHORT.withName("idProduct"),
        JAVA_SHORT.withName("bcdDevice"),
        JAVA_BYTE.withName("iManufacturer"),
        JAVA_BYTE.withName("iProduct"),
        JAVA_BYTE.withName("iSerialNumber"),
        JAVA_BYTE.withName("bNumConfigurations"));

    /**
     * {@code struct timeval}. Windows uses the Winsock definition, two 32-bit
     * {@code long} fields; Linux and macOS use a 64-bit {@code tv_sec}. macOS
     * makes {@code tv_usec} 32 bits, which the trailing padding covers.
     */
    public static final GroupLayout TIMEVAL = isWindows()
        ? structLayout(JAVA_INT.withName("tv_sec"), JAVA_INT.withName("tv_usec"))
        : structLayout(JAVA_LONG.withName("tv_sec"), JAVA_LONG.withName("tv_usec"));

    private Layouts() {
    }

    /** Byte offset of a field within a structure. */
    public static long offset(MemoryLayout layout, String... path) {
        MemoryLayout.PathElement[] elements = new MemoryLayout.PathElement[path.length];
        for (int i = 0; i < path.length; i++) {
            elements[i] = groupElement(path[i]);
        }
        return layout.byteOffset(elements);
    }

    /** Reads an unsigned byte field. */
    public static int u8(MemorySegment segment, GroupLayout layout, String field) {
        return Byte.toUnsignedInt(segment.get(JAVA_BYTE, offset(layout, field)));
    }

    /** Reads an unsigned 16-bit field. */
    public static int u16(MemorySegment segment, GroupLayout layout, String field) {
        return Short.toUnsignedInt(segment.get(JAVA_SHORT, offset(layout, field)));
    }

    /** Allocates a {@code struct timeval} holding a duration. */
    public static MemorySegment timeval(SegmentAllocator allocator, Duration duration) {
        MemorySegment tv = allocator.allocate(TIMEVAL);
        long seconds = duration.toSeconds();
        long micros = duration.toNanosPart() / 1000L;
        if (isWindows()) {
            tv.set(JAVA_INT, offset(TIMEVAL, "tv_sec"), (int) seconds);
            tv.set(JAVA_INT, offset(TIMEVAL, "tv_usec"), (int) micros);
        } else {
            tv.set(JAVA_LONG, offset(TIMEVAL, "tv_sec"), seconds);
            // A long write also fills the 32-bit macOS field: the platforms
            // are little-endian and the upper half is padding there.
            tv.set(JAVA_LONG, offset(TIMEVAL, "tv_usec"), micros);
        }
        return tv;
    }

    private static boolean isWindows() {
        return System.getProperty("os.name").toLowerCase(Locale.ROOT).contains("windows");
    }
}
